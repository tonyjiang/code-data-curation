@pytest.mark.parametrize(
    ("signal", "comparison", "threshold", "reason"),
    QUALITY_RULES,
)
def test_rule_threshold_boundaries(signal, comparison, threshold, reason):
    signals = _passing_signals()
    signals[signal] = threshold
    assert first_rejection(signals) is None
    signals[signal] = (
        threshold - 1 if comparison == "min" and isinstance(threshold, int)
        else threshold - 0.001 if comparison == "min"
        else threshold + 1 if comparison == "max" and isinstance(threshold, int)
        else threshold + 0.001 if comparison == "max"
        else True
    )
    rejection = first_rejection(signals)
    assert rejection is not None
    assert rejection[:2] == (reason, signal)
    assert rejection[2] == signals[signal]
    assert rejection[3] == threshold


def test_rejections_include_precise_metadata():
    repetitive = "\n".join(["result = calculate repeated value"] * 12)
    malformed = "\n".join(
        f"value_{index} = source_{index} + offset_{index}" for index in range(12)
    ) + "\ndef bad(:\n"
    generated = "generated by a tool"
    secret = "api_key = 'abcdefghijk'"
    documents = [
        {"document_id": "repeat", "language": "Python", "content": repetitive},
        {"document_id": "malformed", "language": "Python", "content": malformed},
        {"document_id": "generated", "language": "Python", "content": generated},
        {"document_id": "vendor", "language": "Python", "content": generated, "file_path": "src/vendor/a.py"},
        {"document_id": "secret", "language": "Python", "content": secret},
    ]
    accepted, rejected = quality_filter(documents)
    assert accepted == []
    by_id = {row["document_id"]: row for row in rejected}
    assert by_id["repeat"]["rejection_reason"] == "too_many_duplicate_lines"
    assert by_id["repeat"]["rejection_signal"] == "duplicate_line_fraction"
    assert by_id["generated"]["rejection_signal"] == "generated_marker"
    assert by_id["vendor"]["rejection_signal"] == "is_vendor"
    assert by_id["secret"]["rejection_signal"] == "secret_marker"
    assert by_id["malformed"]["rejection_signal"] == "parse_error"
    assert by_id["malformed"]["quality_signals"]["parse_error"] is True
    assert all("rejection_value" in row and "rejection_threshold" in row for row in rejected)


def test_sample_retains_at_least_half_of_every_language():
    rows = load_jsonl("data/raw/stack-v3-sample.jsonl")
    accepted, _ = quality_filter(rows)
    totals = Counter(row["language"] for row in rows)
    kept = Counter(row["language"] for row in accepted)
    assert set(totals) == set(VALID_SNIPPETS)
    assert all(kept[language] * 2 >= total for language, total in totals.items())



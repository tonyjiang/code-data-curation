@pytest.mark.parametrize(("language", "content"), VALID_SNIPPETS.items())
def test_tree_sitter_parses_each_supported_language(language, content):
    signals = measure_quality(content, language)
    assert signals["parse_supported"] is True
    assert signals["parse_error"] is False


